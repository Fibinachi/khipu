#!/usr/bin/env python3
"""Render the encoded khipu as an SVG image that looks like a real khipu."""
import json

with open("/home/hatch/workspace/quipu-analysis/encoded_khipu_demo.json") as f:
    khipu = json.load(f)

# Color map: Ascher codes to hex
COLORS = {
    "W": "#f5f0e1", "B": "#2b2b2b", "R": "#c0392b", "G": "#27ae60",
    "Y": "#f1c40f", "KB": "#1a1a2e", "AB": "#e67e22", "MB": "#8e44ad",
    "WG": "#d5dbdb", "OB": "#d35400",
}

WIDTH = 900
HEIGHT = 700
TOP_Y = 80

svg = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{WIDTH}" height="{HEIGHT}" viewBox="0 0 {WIDTH} {HEIGHT}">']
svg.append('<rect width="100%" height="100%" fill="#faf8f3"/>')
svg.append('<text x="450" y="30" text-anchor="middle" font-family="Georgia, serif" font-size="20" font-weight="bold">A New Khipu — Encoded 2026-10-12</text>')
svg.append('<text x="450" y="52" text-anchor="middle" font-family="Georgia, serif" font-size="13" fill="#666">Spreadsheet → khipu via structural spec v0.2 | First functionally-encoded khipu in ~400 years</text>')

# Primary cord (horizontal)
svg.append(f'<line x1="100" y1="{TOP_Y}" x2="800" y2="{TOP_Y}" stroke="#8b6914" stroke-width="6" stroke-linecap="round"/>')
svg.append(f'<text x="90" y="{TOP_Y+5}" text-anchor="end" font-family="monospace" font-size="11">P0</text>')

pendants = khipu["children"]
n = len(pendants)
spacing = 600 / max(n, 1)

for i, p in enumerate(pendants):
    x = 200 + i * spacing
    color = COLORS.get(p["color"], "#999")
    dark = "#333" if p["color"] == "W" else color

    # Pendant cord hanging down
    pend_len = 180
    svg.append(f'<line x1="{x}" y1="{TOP_Y}" x2="{x}" y2="{TOP_Y+pend_len}" stroke="{color}" stroke-width="4" stroke-opacity="0.85"/>')

    # Label
    svg.append(f'<text x="{x}" y="{TOP_Y-10}" text-anchor="middle" font-family="monospace" font-size="12" font-weight="bold">{p["label"]}</text>')
    svg.append(f'<text x="{x}" y="{TOP_Y+pend_len+18}" text-anchor="middle" font-family="monospace" font-size="11" fill="#555">Σ={p["value"]:,}</text>')

    # Knot clusters on pendant (summary)
    ky = TOP_Y + 40
    for kc in sorted(p["knots"], key=lambda k: k["position"]):
        # Draw knot as ellipse cluster
        for t in range(min(kc["turns"], 6)):
            kx = x - 8 + t * 3.2
            svg.append(f'<ellipse cx="{kx:.1f}" cy="{ky}" rx="4" ry="6" fill="none" stroke="#333" stroke-width="1.5"/>')
        svg.append(f'<text x="{x+18}" y="{ky+4}" font-family="monospace" font-size="9" fill="#666">10^{kc["position"]}</text>')
        ky += 28

    # Subsidiary cords (branching off)
    subs = p.get("children", [])
    for j, s in enumerate(subs):
        sx = x - 35 + j * 35
        sy_top = TOP_Y + pend_len - 20
        sy_bot = sy_top + 120
        scolor = COLORS.get(s["color"], "#999")
        # Diagonal branch then vertical
        svg.append(f'<line x1="{x}" y1="{sy_top}" x2="{sx}" y2="{sy_top+15}" stroke="{scolor}" stroke-width="2.5"/>')
        svg.append(f'<line x1="{sx}" y1="{sy_top+15}" x2="{sx}" y2="{sy_bot}" stroke="{scolor}" stroke-width="2.5"/>')
        # Small knots for subsidiary value
        sky = sy_top + 35
        for kc in sorted(s["knots"], key=lambda k: k["position"])[:2]:
            for t in range(min(kc["turns"], 4)):
                kkx = sx - 5 + t * 3
                svg.append(f'<ellipse cx="{kkx:.1f}" cy="{sky}" rx="3" ry="4.5" fill="none" stroke="#333" stroke-width="1.2"/>')
            sky += 20
        svg.append(f'<text x="{sx}" y="{sy_bot+14}" text-anchor="middle" font-family="monospace" font-size="9" fill="#555">{s["value"]:,}</text>')

svg.append(f'<text x="450" y="{HEIGHT-20}" text-anchor="middle" font-family="Georgia, serif" font-size="11" fill="#999">Generated by spreadsheet_to_khipu.py | Khipu Data Interchange Format v0.2</text>')
svg.append('</svg>')

out = "/home/hatch/workspace/quipu-analysis/new_khipu_2026.svg"
with open(out, "w") as f:
    f.write("\n".join(svg))
print(f"Saved {out}")

# Also convert to PNG for email attachment
import subprocess
png_out = "/home/hatch/workspace/quipu-analysis/new_khipu_2026.png"
try:
    subprocess.run(["rsvg-convert", "-w", "1800", "-h", "1400", "-o", png_out, out],
                   check=True, capture_output=True)
    print(f"Saved {png_out}")
except Exception as e:
    # Fallback: try cairosvg
    try:
        import cairosvg
        cairosvg.svg2png(url=out, write_to=png_out, scale=2)
        print(f"Saved {png_out} via cairosvg")
    except Exception as e2:
        print(f"PNG conversion failed: {e2}")
        print("SVG only")
